function buildProsCons(id, anchor, tags, type, hot) {
  const r = rng(hashStr(id))
  const pool = PROS_POOL.filter(p => p.when(anchor, tags, type, hot))
  const poolC = CONS_POOL.filter(p => p.when(anchor, tags, type, hot))
  const pick = (pool0, n) => {
    const arr = [...pool0]
    for (let i = arr.length - 1; i > 0; i--) { const j = Math.floor(r() * (i + 1)); [arr[i], arr[j]] = [arr[j], arr[i]] }
    return arr.slice(0, n).map(x => x.t)
  }
  return { pros: pick(pool, Math.min(4, Math.max(3, pool.length))), cons: pick(poolC, Math.min(3, Math.max(2, poolC.length))) }
}

