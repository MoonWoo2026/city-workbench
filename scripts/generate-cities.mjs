function buildConnectivity(cities) {
  // 高铁枢纽：A 全有；D 除空白名单外全有；E 直设名单 + 特注里明显有站的
  const railHubs = cities.filter(c =>
    c.type === '一二线城市'
    || (c.type === '三四线城市' && !RAIL_NO_D[c.name])
    || RAIL_DIRECT_E.has(c.name)
    || (RAIL_NOTES_E[c.name] && /动车|高铁/.test(RAIL_NOTES_E[c.name]) && !/暂无|尚在|无铁路/.test(RAIL_NOTES_E[c.name]))
  )
  const airHubs = cities.filter(c =>
    c.type === '一二线城市' || AIR_D.has(c.name) || AIR_E[c.name]
  )
  const nearest = (c, hubs) => {
    let best = null, bk = Infinity
    for (const h of hubs) {
      if (h.id === c.id) continue
      const k = havKm(c, h)
      if (k < bk) { bk = k; best = h }
    }
    return best ? { hub: best, km: bk } : null
  }
  const hubName = (n, c) => n.province !== c.province ? `${n.province}${n.name}` : n.name

  return cities.map(c => {
    // ---- 高铁文案 ----
    let rail
    if (c.type === '一二线城市') {
      rail = '本市高铁主枢纽，车次密集、地铁直达，周边省份主要城市 1-3 小时当日往返'
    } else if (c.type === '一线郊区' || c.type === '二线郊区') {
      rail = RAIL_BC[c.name] || '母城高铁枢纽乘地铁/城际可达，部分高铁站点就设在本区'
    } else if (RAIL_NO_D[c.name]) {
      rail = RAIL_NO_D[c.name]
    } else if (RAIL_NOTES_E[c.name]) {
      rail = RAIL_NOTES_E[c.name]
    } else if (c.type === '三四线城市') {
      rail = '本市设高铁站（多在新城片区，距老城 15-40 分钟公交/出租），省会及邻省主要城市 1-4 小时可达'
    } else if (RAIL_DIRECT_E.has(c.name)) {
      rail = '县/镇域内设高铁站，可直接乘 D/G 字头动车，接驳车或打车 10-15 分钟到站'
    } else {
      const n = nearest(c, railHubs)
      if (!n) rail = '铁路出行以普速/班车为主'
      else if (n.km <= 50) rail = `就近到${hubName(n.hub, c)}乘高铁（约 ${Math.round(n.km)} 公里，公交/拼车 1 小时内）`
      else if (n.km <= 120) rail = `就近到${hubName(n.hub, c)}乘高铁，公路约 ${Math.round(n.km)} 公里，车程${fmtDrive(n.km, c.province)}`
      else rail = `距最近的高铁枢纽${hubName(n.hub, c)}较远（公路约 ${Math.round(n.km)} 公里），长途出行更依赖航班或自驾`
    }

    // ---- 机场文案 ----
    let air
    if (AIR_BC[c.name]) {
      air = AIR_BC[c.name]
    } else if (AIR_E[c.name]) {
      air = AIR_E[c.name]
    } else if (c.type === '一二线城市') {
      air = '本市大型枢纽机场，轨道交通直达，国内国际航线密集'
    } else if (c.type === '一线郊区' || c.type === '二线郊区') {
      air = '母城大型机场乘机场大巴/轨交约 1 小时可达'
    } else if (AIR_D.has(c.name)) {
      air = '本市有机场，距市区通常 20-40 分钟车程，直飞主要省会城市'
    } else {
      const n = nearest(c, airHubs)
      if (!n) air = '本地无民用机场，出行以高铁/公路为主'
      else if (n.km <= 70) air = `就近${hubName(n.hub, c)}机场（约 ${Math.round(n.km)} 公里，1 小时车程内）`
      else if (n.km <= 170) air = `乘飞机就近到${hubName(n.hub, c)}（公路约 ${Math.round(n.km)} 公里，车程${fmtDrive(n.km, c.province)}）`
      else air = `距最近机场${hubName(n.hub, c)}较远（约 ${Math.round(n.km)} 公里），可先飞省会再转高铁/大巴`
    }

    return { ...c, net: { broadband: broadbandText(c), cowork: coworkText(c) }, transit: { taxi: taxiText(c), rail, air } }
  })
}

