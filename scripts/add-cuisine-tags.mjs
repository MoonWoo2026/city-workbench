let h = 0, l = 0, hv = 0
for (const name of HOMELY) {
  if (!cities[name]) continue
  if (!cities[name].g.includes('家常')) { cities[name].g.push('家常'); h++ }
}
for (const name of LIGHT) {
  if (!cities[name]) continue
  if (!cities[name].g.includes('清淡')) { cities[name].g.push('清淡'); l++ }
}
